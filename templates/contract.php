<article class="contract">
<h1>Contrat officiel du jeu « Tous en couple »</h1>
<div class="card">

<h2>Entre les soussignés</h2>
<p>Les personnes qui apposent leur signature au pied du présent contrat, ci-après dénommées individuellement « le Membre » et collectivement « les Membres ». Chaque Membre signe son propre exemplaire ; l'ensemble des exemplaires signés forme un seul et même contrat.</p>

<h2>Préambule</h2>
<p>Né du défi « tous en couple » de juillet 2026, le présent contrat fixe les règles du jeu pluriannuel auquel les Membres choisissent de continuer à jouer. Chaque année, ils se retrouvent, présentent leur situation sentimentale, et un barème de points désigne un gagnant annuel, puis un gagnant du classement global tous les trois ans.</p>
<p>Les règles ont été équilibrées par simulation. Les différences avec la première version du barème sont listées dans le document annexe « Amendements de l'année 0 », qui sert de guide pour toute proposition de modification.</p>
<p><strong>Il a été convenu et arrêté ce qui suit :</strong></p>

<h2>Article 1 : Définitions</h2>
<ul>
<li><strong>Année de jeu</strong> : période entre deux réunions. Les points d'une année sont constatés à la réunion qui la clôt.</li>
<li><strong>Couple</strong> : relation amoureuse réelle entre un Membre et une personne, que le Membre présente comme son partenaire. Le barème des articles 4 et 5 définit ce qui rapporte ou coûte des points ; ce qui n'y figure pas ne compte pas.</li>
<li><strong>Partenaire</strong> : la personne avec laquelle le Membre est en couple.</li>
<li><strong>Présentation officielle</strong> : première fois qu'un Membre présente un partenaire au groupe, en personne ou, dans les cas prévus à l'article 2, en visio.</li>
<li><strong>Faux partenaire</strong> : personne présentée comme partenaire alors qu'il n'y a pas de relation amoureuse (voir le bluff, article 4).</li>
<li><strong>Site</strong> : l'application web du jeu, où sont déclarés les statuts, les événements, les votes et les classements.</li>
<li><strong>Administrateur</strong> : Membre qui valide les saisies sur le site (voir article 3).</li>
<li><strong>Soirée</strong> : le temps de la réunion où les Membres présentent leur situation, accusent, votent et décernent les prix.</li>
</ul>

<h2>Article 2 : Réunion annuelle</h2>
<p><strong>2.1. Période.</strong> Les Membres se réunissent chaque année en juillet ou août, à une date convenue à l'avance qui convient à tous. Si la réunion est impossible en juillet-août, elle est reportée de 6 mois au plus.</p>
<p><strong>2.2. Présence.</strong> Chaque Membre se rend à la réunion et y présente sa situation sentimentale actuelle.</p>
<p><strong>2.3. Hôte.</strong> Un Membre reçoit la réunion (volontaire, sinon tirage au sort) et gagne +3 points. Un Membre ne peut pas être hôte deux années de suite.</p>
<p><strong>2.4. Déplacement.</strong> Les Membres qui se déplacent gagnent un bonus selon la distance jusqu'au lieu de l'hôte :</p>
<table><thead><tr><th>Distance</th><th>Bonus</th></tr></thead><tbody>
<tr><td>moins de 300 km</td><td>0</td></tr>
<tr><td>300 à 1 500 km</td><td>0</td></tr>
<tr><td>1 500 à 6 000 km</td><td>+1</td></tr>
<tr><td>plus de 6 000 km</td><td>+1</td></tr>
</tbody></table>
<p><strong>2.5. Partenaire lointain en visio.</strong> Un partenaire trop éloigné peut participer en visio s'il a été présenté en personne au moins une fois. Après 2 années de suite en visio, la 3e année sans présence réelle compte comme une absence du partenaire (2.7).</p>
<p><strong>2.6. Retard et absence du Membre.</strong></p>
<ul>
<li>Retard de plus de 30 minutes sans avoir prévenu avant l'heure convenue : −1 point.</li>
<li>Absence prévenue moins de 15 jours à l'avance, ou sans raison valable (jugée à la majorité simple des autres Membres) : −1 point et aucun gain pour l'année.</li>
<li>Absence du Membre avec une rupture dans l'année : pas de gel, le malus de rupture s'applique et −1 point de fuite s'y ajoute.</li>
</ul>
<p><strong>2.7. Absence du partenaire : gel.</strong> Si le partenaire est absent, la série du Membre est conservée mais l'année ne rapporte pas de points de série. Les étapes de vie de l'année sont reportées à la réunion suivante. Les malus de tromperie, de fin de vie commune et de rupture cachée s'appliquent quand même. L'hôte garde son bonus.</p>

<h2>Article 3 : Déclarations et site</h2>
<p><strong>3.1. Registre.</strong> Le site est le registre du jeu. Chaque Membre y déclare, avant la réunion, son statut réel et les événements de l'année (rupture, étape de vie, bluff, tentative). Les déclarations sont horodatées et croisées avec ce que chacun annonce à la soirée.</p>
<p><strong>3.2. Confiance.</strong> Les déclarations reposent sur la bonne foi. Aucune preuve n'est exigée et la tromperie n'est jugée par aucun vote.</p>
<p><strong>3.3. Validation.</strong> L'administrateur valide les saisies. Le classement et les informations publiques (absences avec motif, hôte de l'année) sont visibles de tous ; chaque Membre a un espace privé avec son statut et ses saisies.</p>
<p><strong>3.4. Vote en direct.</strong> Les accusations de bluff et les prix se votent pendant la soirée, sur le site.</p>

<h2>Article 4 : Barème des points annuels</h2>
<p><strong>4.1. Série.</strong> Chaque année passée en couple avec le même partenaire rapporte :</p>
<table><thead><tr><th>Année avec le même partenaire</th><th>Points</th></tr></thead><tbody>
<tr><td>1re (présentation officielle)</td><td>+2</td></tr>
<tr><td>2e</td><td>+2</td></tr>
<tr><td>3e</td><td>+3</td></tr>
<tr><td>4e</td><td>+4</td></tr>
<tr><td>5e et suivantes</td><td>+5 par an</td></tr>
</tbody></table>
<p>La série repart du début après une rupture, un changement de partenaire ou une venue célibataire. Une rupture suivie d'une remise ensemble repart aussi du début. La fin de vie commune ou du PACS avec un couple qui continue ne casse pas la série.</p>
<p><strong>4.2. Étapes de vie.</strong> Chacune rapporte ses points une seule fois par relation et se cumule avec les autres :</p>
<table><thead><tr><th>Étape</th><th>Points</th></tr></thead><tbody>
<tr><td>Emménagement ensemble (aussi si l'un s'installe chez l'autre pour de vrai)</td><td>+2</td></tr>
<tr><td>Achat commun</td><td>+3</td></tr>
<tr><td>Fiançailles</td><td>+3</td></tr>
<tr><td>PACS</td><td>+3</td></tr>
<tr><td>Mariage</td><td>+5</td></tr>
<tr><td>Enfant (chaque enfant)</td><td>+5</td></tr>
</tbody></table>
<p><strong>4.3. Malus de rupture.</strong> Une seule rupture donne un seul malus, le plus élevé qui s'applique :</p>
<table><thead><tr><th>Événement</th><th>Points</th></tr></thead><tbody>
<tr><td>Rupture simple</td><td>−2</td></tr>
<tr><td>Fin de vie commune ou de PACS</td><td>−3</td></tr>
<tr><td>Divorce</td><td>−5</td></tr>
<tr><td>Rupture entre les fiançailles et le mariage</td><td>−8</td></tr>
<tr><td>Tromperie (surtout infidélité), déclarée à la confiance</td><td>−10</td></tr>
<tr><td>Rupture cachée au groupe (en plus du malus de rupture)</td><td>−3</td></tr>
</tbody></table>
<p>Il n'y a pas de malus pour un célibat prolongé ni pour un changement de partenaire.</p>
<p><strong>4.4. Rupture en bons termes.</strong> Si les Membres le jugent à la majorité simple (l'ex est appelé pendant la soirée, sans enregistrement), le malus de rupture est annulé mais la série est cassée. La tromperie n'est jamais annulée.</p>
<p><strong>4.5. Bluff.</strong> Un Membre peut présenter un faux partenaire s'il l'a déclaré sur le site avant la réunion.</p>
<ul>
<li>Bluff réussi : +3 points. Il ne crée ni série ni étape de vie.</li>
<li>Bluff démasqué par au moins un Membre : −5 points.</li>
<li>Seul accusateur correct : +2 points.</li>
<li>Accusation à tort : −1 point.</li>
<li>Même faux partenaire deux années de suite : +1 point, une seule fois.</li>
</ul>
<p><strong>4.6. Tentative.</strong> Un Membre célibataire gagne +1 point par an au maximum pour une tentative déclarée (compte actif sur une application de rencontre, rendez-vous, activité pour rencontrer du monde, rencontre arrangée).</p>
<p><strong>4.7. Prix et mentions.</strong> Deux par an sont décernés pendant la soirée par vote de fin de soirée (pas pour soi, au maximum un par Membre), +1 point chacun.</p>
<p><strong>4.8. Plancher.</strong> Le total annuel d'un Membre ne descend jamais sous 0.</p>

<h2>Article 5 : Classements et récompenses</h2>
<p><strong>5.1. Classement annuel.</strong> Remis à zéro à chaque réunion. Le Membre qui totalise le plus de points est premier. En cas d'égalité, chacun garde la meilleure place.</p>
<p><strong>5.2. Rattrapage.</strong> Au début de l'année suivante, le dernier du classement annuel précédent gagne +1 point (tous les derniers ex æquo l'obtiennent, sauf si tous les Membres sont à égalité).</p>
<p><strong>5.3. Classement global.</strong> À chaque réunion, chaque Membre reçoit des points selon son rang annuel :</p>
<table><thead><tr><th>Rang annuel</th><th>Points globaux</th></tr></thead><tbody>
<tr><td>1er</td><td>3</td></tr>
<tr><td>2e</td><td>2</td></tr>
<tr><td>3e</td><td>1</td></tr>
<tr><td>4e et suivants</td><td>0</td></tr>
</tbody></table>
<p>Le global est ensuite calculé ainsi : global = 0,7 × global précédent + points de l'année (une décimale). Les points anciens comptent donc de moins en moins. Le global ne descend jamais sous 0. En cas d'égalité annuelle, chacun prend les points de la meilleure place.</p>
<p><strong>5.4. Cadeau annuel.</strong> Les derniers offrent aux premiers, en miroir : le dernier au premier, l'avant-dernier au deuxième, et ainsi de suite. Un Membre placé exactement au milieu du classement ne donne ni ne reçoit. Le budget par paire est fixé à l'avance (le 1er est le mieux servi), la forme est libre (restaurant, activité…) et la remise a lieu dans le mois suivant la réunion. En cas d'égalité, les cadeaux ont la même valeur.</p>
<p><strong>5.5. Cadeau global, tous les 3 ans.</strong> Le 1er du classement global reçoit un cadeau commun des autres Membres. En cas d'égalité, le plus gros total de points annuels sur les 3 ans l'emporte ; si l'égalité persiste, les deux le reçoivent. Le cadeau annuel et le cadeau global restent deux récompenses distinctes.</p>

<h2>Article 6 : Nouveaux joueurs</h2>
<p><strong>6.1. Admission.</strong> Un Membre qui veut inviter quelqu'un présente ses arguments. Les autres délibèrent sans lui ; l'unanimité des autres Membres est requise. Le coût d'entrée est fixé dans le même vote.</p>
<p><strong>6.2. Points de départ.</strong> Le nouveau joueur commence avec max(0 ; points du dernier − H), où H = min(3 ; max(1 ; écart médian entre joueurs consécutifs arrondi au supérieur)). Il n'y a pas de règle de sortie d'un joueur.</p>

<h2>Article 7 : Avenants</h2>
<p><strong>7.1. Dépôt.</strong> Tout Membre peut proposer une modification des règles sur le site pendant les 4 mois qui précèdent la réunion. La plateforme ferme 1 semaine avant la réunion.</p>
<p><strong>7.2. Vote.</strong> Majorité simple des suffrages exprimés ; une égalité vaut rejet. Le résultat est annoncé pendant la soirée.</p>
<p><strong>7.3. Application.</strong> Les modifications adoptées s'appliquent à l'année de jeu suivante.</p>
<p><strong>7.4. Annexe.</strong> Le document « Amendements de l'année 0 » liste les 9 différences entre la version d'origine et le barème du présent contrat, et l'effet mesuré d'une modification de chacune.</p>

<h2>Article 8 : Portée du contrat</h2>
<p>Ce contrat est symbolique et ludique. Il n'a de valeur juridique que dans l'univers du jeu, où les Membres le tiennent pour irrévocable et exécutoire. Il engage l'honneur des Membres, pas leur patrimoine : un cadeau ou un dîner non remis ne donne lieu à aucune action en justice.</p>

